import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {transform} from 'esbuild';
import {randomBytes,scryptSync} from 'node:crypto';
const {code}=await transform(readFileSync('src/lib/redshift-auth.ts','utf8'),{loader:'ts',format:'esm'});
const auth=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const salt=randomBytes(16).toString('hex');
process.env.REDSHIFT_ACCESS_CONFIG=JSON.stringify({salt,hash:scryptSync('test-password',salt,64).toString('hex'),secret:randomBytes(32).toString('hex')});
assert(auth.checkPassword('test-password'));
assert(!auth.checkPassword('wrong'));
assert(!auth.checkPassword('x'.repeat(257)));
const session=auth.createSession();
assert(auth.authorized(session));
assert(!auth.authorized(session.slice(0,-1)+(session.endsWith('0')?'1':'0')));
assert(!auth.authorized(session,Date.now()+auth.MAX_AGE*1000+1000));
assert(!auth.authorized(undefined));
assert(auth.sameOrigin(new Request('https://www.deannaglaze.com/api/redshift/access',{headers:{origin:'https://www.deannaglaze.com'}})));
assert(!auth.sameOrigin(new Request('https://www.deannaglaze.com/api/redshift/access',{headers:{origin:'https://evil.example'}})));
process.env.REDSHIFT_ACCESS_CONFIG='invalid';
assert(!auth.authorized(session));
assert(!auth.checkPassword('test-password'));
console.log('Passed: password validation, signed sessions, tampering, expiry, origin checks and fail-closed configuration.');
